package ru.ovd.fitness.core.data.entity

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * Контрольное упражнение по физической подготовке.
 *
 * Источник: приказ МВД № 44, пункт 343.
 *
 * Упражнения различаются для мужчин и женщин:
 *   Мужчины (10 упражнений):
 *     1. Подтягивание на перекладине
 *     2. Жим гири весом 24 килограмма
 *     3. Сгибание и разгибание рук в упоре лёжа
 *     4. Челночный бег 10x10 метров
 *     5. Челночный бег 4x20 метров
 *     6. Бег (кросс) на 3 километра
 *     7. Бег (кросс) на 5 километров
 *     8. Бег на лыжах на 5 километров
 *     9. Плавание на 100 метров
 *
 *   Женщины (8 упражнений):
 *     1. Сгибание и разгибание рук в упоре лёжа
 *     2. Наклоны вперёд из положения лёжа на спине
 *     3. Челночный бег 10x10 метров
 *     4. Бег (кросс) на 1 километр
 *     5. Бег (кросс) на 3 километра
 *     6. Бег на лыжах на 5 километров
 *     7. Плавание на 100 метров
 *
 * Поле unit — единица измерения: "раз", "секунд", "минут, секунд".
 * Поле category — категория: "Сила", "Быстрота и ловкость", "Выносливость".
 */
@Entity(tableName = "exercises")
data class Exercise(
    @PrimaryKey(autoGenerate = true)
    val id: Int = 0,

    /** Пол: "male" / "female" */
    val gender: String,

    /** Порядковый номер в таблице приказа (от 1) */
    val orderNumber: Int,

    /** Название упражнения */
    val name: String,

    /** Единица измерения: "раз", "секунд", "минут, секунд" */
    val unit: String,

    /** Категория: "Сила", "Быстрота и ловкость", "Выносливость" */
    val category: String
)
